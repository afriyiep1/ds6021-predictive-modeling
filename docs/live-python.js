(()=>{'use strict';
const script=document.currentScript;
const base=new URL('./',script.src);
let worker=null,active=null,timer=null;
function controls(busy){document.querySelectorAll('[data-run-python]').forEach(b=>b.disabled=busy);document.querySelectorAll('[data-stop-python]').forEach(b=>b.disabled=!busy||b.closest('.live-python')!==active);}
function finish(){clearTimeout(timer);controls(false);active=null;}
function terminate(message){if(worker){worker.terminate();worker=null;}if(active)active.querySelector('[role="status"]').textContent=message;finish();}
function createWorker(){
 worker=new Worker(new URL('python-worker.js',base),{type:'module'});
 worker.onmessage=({data})=>{
  if(!active)return;
  const status=active.querySelector('[role="status"]');
  if(data.type==='status'){status.textContent=data.text;return;}
  if(data.type==='error'){terminate(data.text);return;}
  if(data.type==='result'){
   const output=active.querySelector('.live-output');output.replaceChildren();
   const label=document.createElement('p');label.className='output-label';label.textContent='YOUR BROWSER RESULT';output.append(label);
   if(data.text){const pre=document.createElement('pre');pre.className='notebook-text';pre.textContent=data.text;output.append(pre);}
   for(const bytes of data.images){const img=document.createElement('img');img.src='data:image/png;base64,'+bytes;img.alt='Plot generated by the Python example';img.className='notebook-image';output.append(img);}
   if(data.error){const pre=document.createElement('pre');pre.className='python-error';pre.textContent=data.error;output.append(pre);status.textContent='The code stopped with an error. Edit the code and try again.';}
   else status.textContent='Finished. Results above were computed on this device.';
   finish();
  }
 };
 worker.onerror=()=>terminate('Python could not start. Check your network connection or download the example for Colab.');
}
document.querySelectorAll('.live-python').forEach(panel=>{
 const editor=panel.querySelector('textarea');const original=editor.value;
 panel.querySelector('[data-run-python]').addEventListener('click',()=>{
  if(active)return;active=panel;controls(true);panel.querySelector('[role="status"]').textContent='Starting Python…';
  if(!worker)createWorker();
  worker.postMessage({code:editor.value,base:base.href});
  timer=setTimeout(()=>terminate('Stopped after five minutes. Reduce the computation and try again.'),300000);
 });
 panel.querySelector('[data-stop-python]').addEventListener('click',()=>terminate('Stopped. Previous displayed results have been kept.'));
 panel.querySelector('[data-reset-python]').addEventListener('click',()=>{if(active===panel)terminate('Stopped.');editor.value=original;panel.querySelector('[role="status"]').textContent='Code reset. Run it to refresh the results.';});
 editor.addEventListener('keydown',e=>{if(e.key==='Tab'){e.preventDefault();const s=editor.selectionStart,t=editor.selectionEnd;editor.setRangeText('    ',s,t,'end');}});
});
document.querySelectorAll('[data-code-visibility]').forEach(button=>button.addEventListener('click',()=>{
 const open=button.getAttribute('aria-pressed')!=='true';document.querySelectorAll('details.code-reveal').forEach(d=>d.open=open);button.setAttribute('aria-pressed',String(open));button.textContent=open?'Hide all code':'Show all code';
}));
})();
